def docutoff(vgp_block,angle=45,di_block=0,plot=False):
    """
    Applies fixed cutoff to set of Virtual Geomagnetic Poles. Default is 45 degrees. 

    Parameters
    -----------
    vgp_block : a nested list of VGPs
    
    Optional Parameters (defaults are used if not specified)
    -----------
    angle : fixed cutoff angle from mean of VGPs
    di_block : a nested list of directions 
    plot : plots VGPs per iteration of cutoff procedure (red if rejected)

    Return
    -----------
    vgp_block : a nested list of VGPs after applying fixed angle cutoff
    vgp_block_rejected : a nested list of rejected VGPs
    di_block : a nested list of accepted directions (if di_block is specified)
    di_block_rejected : a nested list of rejected directions (if di_block is specified)
    """

    vgp_block_rejected=[]
    di_block_rejected=[]

    while True:
        vgp_mean = pmag.fisher_mean(vgp_block)  # calculate Fisher (1953) mean of VGPs
        ref_mean=[vgp_mean['dec'],vgp_mean['inc']]  # store mean longitude and latitude

        cutoffangle=angle   # store fixed cutoff angle, default is 45 degrees
        for i in range(len(vgp_block)): # loop through all VGPs
            angletomean=pmag.angle(vgp_block[i],ref_mean)   # calculate angle between VGP and mean
            if angletomean > cutoffangle:   # check if angle exceeds cutoff angle
                cutoffangle=angletomean     # store maximum angle 
                index=i                     # store index of VGP with maximum angle

        if cutoffangle==angle:  # if no angle exceeds cutoff angle, end algorithm
            break

        vgp_block_rejected.append(vgp_block[index]) # add rejected VGP to list
        vgp_block=np.delete(vgp_block,index,axis=0)
        #del vgp_block[index] # remove rejected VGP from original list of VGPs

        di_block_rejected.append(di_block[index]) # add rejected direction to list
        di_block=np.delete(di_block,index,axis=0)
        #del di_block[index] # remove rejected VGP from original list of directions
            

    # Plotting
    if plot==True:
        fignum = 1
        ipmag.plot_net(fignum)   # plot equal area projection
        ipmag.plot_di(di_block=di_block,color='darkgreen',edge='black',marker='o',markersize=40,label='accepted')
        ipmag.plot_di(di_block=di_block_rejected,color='red',edge='black',marker='o',markersize=40,label='rejected')
        ipmag.plot_di_mean(dec=vgp_mean['dec'],inc=vgp_mean['inc'],a95=angle,color='black',marker='*',markersize=100,label='mean of accepted VGPs')
        plt.legend(loc=1,fontsize='large')
        plt.show()

    return vgp_block,vgp_block_rejected,di_block,di_block_rejected

def donewvandamme(vgp_block,di_block=0,plot=False):
    """
    Applies the Vandamme (1994) to set of Virtual Geomagnetic Poles. Follows recursive method of figure 5 of original publication.

    Parameters
    -----------
    vgp_block : a nested list of VGPs
    
    Optional Parameters (defaults are used if not specified)
    -----------
    plot : plots VGPs per iteration of cutoff procedure (red if rejected)
    di_block : a nested list of directions 

    Return
    -----------
    vgp_block : a nested list of VGPs after applying fixed angle cutoff
    vgp_block_rejected : a nested list of rejected VGPs
    ASD : angular standard deviation after cutoff
    A : cutoff angle
    di_block : a nested list of accepted directions (if di_block is specified)
    di_block_rejected : a nested list of rejected directions (if di_block is specified)
    """
    
    vgp_block_rejected=[]
    di_block_rejected=[]
    
    while True:
        vgp_mean = pmag.fisher_mean(vgp_block)  # calculate Fisher (1953) mean of VGPs
        ref_mean=[vgp_mean['dec'],vgp_mean['inc']]  # store mean longitude and latitude

        maxangle=0
        deltasum=0
        N=len(vgp_block)
        for i in range(N): # loop through all VGPs
            angletomean=pmag.angle(vgp_block[i],ref_mean)   # calculate angle between VGP and mean
            if angletomean[0] > maxangle:   # check if angle exceeds largest angle
                maxangle=angletomean[0]     # store maximum angle 
                index=i                        # store index of VGP with maximum angle
            deltasum+=math.pow(angletomean[0],2) # add angle to sum of squared angles

        # Apply method of Vandamme (1994)
        ASD=math.sqrt(deltasum/(N-1)) # calculate angular standard deviation
        A=1.8 * ASD + 5. # calculate optimum cutoff angle (A)

        if maxangle<A:  # if largest angle does not exceed optimum cutoff angle, end algorithm
            break

        vgp_block_rejected.append(vgp_block[index]) # add rejected VGP to list
        vgp_block=np.delete(vgp_block,index,axis=0)
        #del vgp_block[index] # remove rejected VGP from original list of VGPs

        di_block_rejected.append(di_block[index]) # add rejected direction to list
        di_block=np.delete(di_block,index,axis=0)

        # Plotting
        if plot==True:
            fignum = 1
            ipmag.plot_net(fignum)   # plot equal area projection
            ipmag.plot_di(di_block=vgp_block,color='darkgreen',edge='black',marker='o',markersize=40,label='accepted')
            ipmag.plot_di(di_block=vgp_block_rejected,color='red',edge='black',marker='o',markersize=40,label='rejected')
            plot_di_mean(dec=vgp_mean['dec'],inc=vgp_mean['inc'],a95=A,color='black',edge='black',marker='*',markersize=100,label='mean of accepted VGPs')
            plt.legend(loc=1,fontsize='large')
            plt.show()
            
    print('ASD = %1.1f' % ASD)
    print('Cutoff angle = %1.1f' % A)

    return vgp_block,vgp_block_rejected,di_block,di_block_rejected

def di2vgp(di_block,slat=0,slon=0,samp_loc=0):
    """
    Converts directional data (declination, inclination) at a given sampling
    location (Site latitude, Site longitude) to pole position (pole longitude,
    pole latitude)

    Required Parameters
    -----------
    di_block : nested list of direction given as [declination,inclination] 
    slat : sampling latitude
    slon : sampling longitude
    samp_loc : sampling location(s) given as nested list of [site LATITUDE, site LONGITUDE]

    Return
    -----------
    plat : latitude of VGP (or pole) associates with paleomagnetic direction assuming a GAD field
    plon : longitude of VGP (or pole) associates with paleomagnetic direction assuming a GAD field
    """
    # check number of directions
    n_dirs = len(di_block)

    # check if there are multiple sampling locations
    if samp_loc==0:

        input_list=[[di_block[k][0],di_block[k][1],0,slat,slon] for k in range(n_dirs)]
        output_list=pmag.dia_vgp(input_list)
        vgp_block=[[output_list[0][k],output_list[1][k]] for k in range(n_dirs)]

    else:
        n_locs = len(samp_loc)

        if n_dirs!=n_locs:
            print('ERROR: NUMBER OF LOCATIONS ARE NOT EQUAL TO NUMBER OF DIRECTIONS')
        else:
            input_list=[[di_block[k][0],di_block[k][1],0,samp_loc[k][0],samp_loc[k][1]] for k in range(n_dirs)]
            output_list=pmag.dia_vgp(input_list)
            vgp_block=[[output_list[0][k],output_list[1][k]] for k in range(n_dirs)]

    return vgp_block


def find_ei(data, nb=1000, save=False, save_folder='.', fmt='svg',
            site_correction=False, return_new_dirs=False, params=False):
    """
    Applies series of assumed flattening factor and "unsquishes" inclinations assuming tangent function.
    Finds flattening factor that gives elongation/inclination pair consistent with TK03;
    or, if correcting by site instead of for study-level secular variation,
    finds flattening factor that minimizes elongation and most resembles a
    Fisherian distribution.
    Finds bootstrap confidence bounds
    Required Parameter
    -----------
    data: a nested list of dec/inc pairs
    Optional Parameters (defaults are used unless specified)
    -----------
    nb: number of bootstrapped pseudo-samples (default is 1000)
    save: Boolean argument to save plots (default is False)
    save_folder: path to folder in which plots should be saved (default is current directory)
    fmt: specify format of saved plots (default is 'svg')
    site_correction: Boolean argument to specify whether to "unsquish" data to
        1) the elongation/inclination pair consistent with TK03 secular variation model
        (site_correction = False)
        or
        2) a Fisherian distribution (site_correction = True). Default is FALSE.
        Note that many directions (~ 100) are needed for this correction to be reliable.
    return_new_dirs: optional return of newly "unflattened" directions (default is False)
    Returns
    -----------
    four plots:   1) equal area plot of original directions
                  2) Elongation/inclination pairs as a function of f,  data plus 25 bootstrap samples
                  3) Cumulative distribution of bootstrapped optimal inclinations plus uncertainties.
                     Estimate from original data set plotted as solid line
                  4) Orientation of principle direction through unflattening
    NOTE: If distribution does not have a solution, plot labeled: Pathological.  Some bootstrap samples may have
       valid solutions and those are plotted in the CDFs and E/I plot.
    """
    print("Bootstrapping.... be patient")
    print("")
    sys.stdout.flush()

    upper, lower = int(round(.975 * nb)), int(round(.025 * nb))
    E, I = [], []

    plt.figure(num=1, figsize=(4.5, 4.5))
    ipmag.plot_net(1)
    ipmag.plot_di(di_block=data)
    plt.title('Original')
    ppars = pmag.doprinc(data)
    Io = ppars['inc']
    n = ppars["N"]
    Es, Is, Fs, V2s = pmag.find_f(data)
    if site_correction == True:
        Inc, Elong = Is[Es.index(min(Es))], Es[Es.index(min(Es))]
        flat_f = Fs[Es.index(min(Es))]
    else:
        Inc, Elong = Is[-1], Es[-1]
        flat_f = Fs[-1]

    if (Inc, Elong, flat_f) == (0, 0, 0):
        print("NO INTERSECTION WITH E/I CURVE")
    else:
        plt.figure(num=2, figsize=(4.5,4.5))
        plt.plot(Is, Es, 'r')
        plt.xlabel("Inclination")
        plt.ylabel("Elongation")
