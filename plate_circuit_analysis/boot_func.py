def plot_ell(fignum, pars, col, lower, plot):
    """
    function to calcualte/plot points on an ellipse about Pdec,Pdip with angle beta,gamma
    Parameters
    _________
    fignum : matplotlib figure number
    pars : list of [Pdec, Pinc, beta, Bdec, Binc, gamma, Gdec, Ginc ]
         where P is direction, Bdec,Binc are beta direction, and Gdec,Ginc are gamma direction
    col : color for ellipse
    lower : boolean, if True, lower hemisphere projection
    plot : boolean, if False, return the points, if False, make the plot
    """
    #plt.figure(num=fignum)
    rad = old_div(np.pi, 180.)
    Pdec, Pinc, beta, Bdec, Binc, gamma, Gdec, Ginc = pars[0], pars[
        1], pars[2], pars[3], pars[4], pars[5], pars[6], pars[7]
    if beta > 90. or gamma > 90:
        beta = 180. - beta
        gamma = 180. - gamma
        Pdec = Pdec - 180.
        Pinc = -Pinc
    beta, gamma = beta * rad, gamma * rad  # convert to radians
    X_ell, Y_ell, X_up, Y_up, PTS = [], [], [], [], []
    nums = 201
    xnum = old_div(float(nums - 1.), 2.)
# set up t matrix
    t = [[0, 0, 0], [0, 0, 0], [0, 0, 0]]
    X = pmag.dir2cart((Pdec, Pinc, 1.0))  # convert to cartesian coordintes
    if lower == 1 and X[2] < 0:
        for i in range(3):
            X[i] = -X[i]
# set up rotation matrix t
    t[0][2] = X[0]
    t[1][2] = X[1]
    t[2][2] = X[2]
    X = pmag.dir2cart((Bdec, Binc, 1.0))
    if lower == 1 and X[2] < 0:
        for i in range(3):
            X[i] = -X[i]
    t[0][0] = X[0]
    t[1][0] = X[1]
    t[2][0] = X[2]
    X = pmag.dir2cart((Gdec, Ginc, 1.0))
    if lower == 1 and X[2] < 0:
        for i in range(3):
            X[i] = -X[i]
    t[0][1] = X[0]
    t[1][1] = X[1]
    t[2][1] = X[2]
# set up v matrix
    v = [0, 0, 0]
    for i in range(nums):  # incremental point along ellipse
        psi = float(i) * np.pi / xnum
        v[0] = np.sin(beta) * np.cos(psi)
        v[1] = np.sin(gamma) * np.sin(psi)
        v[2] = np.sqrt(1. - v[0]**2 - v[1]**2)
        elli = [0, 0, 0]
# calculate points on the ellipse
        for j in range(3):
            for k in range(3):
                # cartesian coordinate j of ellipse
                elli[j] = elli[j] + t[j][k] * v[k]
        pts = pmag.cart2dir(elli)
        PTS.append([pts[0], pts[1]])
        # put on an equal area projection
        R = old_div(np.sqrt(
            1. - abs(elli[2])), (np.sqrt(elli[0]**2 + elli[1]**2)))
        if elli[2] <= 0:
            #            for i in range(3): elli[i]=-elli[i]
            X_up.append(elli[1] * R)
            Y_up.append(elli[0] * R)
        else:
            X_ell.append(elli[1] * R)
            Y_ell.append(elli[0] * R)
    if plot == 1:
        col = col[0]+'.'
        if X_ell != []:
            plt.plot(X_ell, Y_ell, col, markersize=3)
        if X_up != []:
            plt.plot(X_up, Y_up, col, markersize=3)
    else:
        return PTS

def circ(dec, dip, alpha, n_points=201):
    """
    function to calculate points on an circle about dec,dip with angle alpha
    """
    rad = old_div(np.pi, 180.)
    D_out, I_out = [], []
    dec, dip, alpha = dec * rad, dip * rad, alpha * rad
    dec1 = dec + old_div(np.pi, 2.)
    isign = 1
    if dip != 0:
        isign = (old_div(abs(dip), dip))
    dip1 = (dip - isign * (old_div(np.pi, 2.)))
    t = [[0, 0, 0], [0, 0, 0], [0, 0, 0]]
    v = [0, 0, 0]
    t[0][2] = np.cos(dec) * np.cos(dip)
    t[1][2] = np.sin(dec) * np.cos(dip)
    t[2][2] = np.sin(dip)
    t[0][1] = np.cos(dec) * np.cos(dip1)
    t[1][1] = np.sin(dec) * np.cos(dip1)
    t[2][1] = np.sin(dip1)
    t[0][0] = np.cos(dec1)
    t[1][0] = np.sin(dec1)
    t[2][0] = 0
    for i in range(n_points):
        psi = float(i) * np.pi / ((n_points-1)/4)
        v[0] = np.sin(alpha) * np.cos(psi)
        v[1] = np.sin(alpha) * np.sin(psi)
        v[2] = np.sqrt(abs(1. - v[0]**2 - v[1]**2))
        elli = [0, 0, 0]
        for j in range(3):
            for k in range(3):
                elli[j] = elli[j] + t[j][k] * v[k]
        Dir = pmag.cart2dir(elli)
        D_out.append(Dir[0])
        I_out.append(Dir[1])
    return D_out, I_out

def in_ellipse(center,x_co,y_co,points,scatter='no'):
    """
    Determines if points is located inside ellipse (or circle).
    Parameters
    -----------
    center : list of x and y coordinate of center of ellipse (or circle)
    x_co   : list of x coordinates defining ellipse (or circle)
    y_co   : list of y coordinates defining ellipse (or circle)
    points  : nested list of x and y coordinates of points that will be tested'
    scatter : if 'yes', plots the input points red (if inside ellipse) or blue (outside ellipse)
    
    Return
    -----------
    location: list of 'in' or 'out' statements to indicate if point is inside ellipse

    """
    d=[]
    x_center,y_center=center[0],center[1]   # store x and y coordinate of center
    xs_out,ys_out,xs_in,ys_in=[],[],[],[]
        
    for k in range(len(points)):
        x_point,y_point=points[k][0],points[k][1]
        for i in range(len(x_co)):  # loop through number of ellipse points
         d_to_ellipse_point=np.sqrt((x_co[i]-x_point)**2+(y_co[i]-y_point)**2)    # calculate distance from point to ellipse point
         d.append(d_to_ellipse_point)   # store distances
        d_min=min(d)                    # distance of point to closest ellipse point
        indx=d.index(d_min)                 # get index of closest ellipse point
        x_ell,y_ell=x_co[indx],y_co[indx]   # get coordinates of closest ellipse point

        R1=np.sqrt((x_point-x_center)**2+(y_point-y_center)**2)     # calculate distance from point to center
        R2=np.sqrt((x_ell-x_center)**2+(y_ell-y_center)**2)         # calculate distance from ellipse point to center
        if R1>R2:       # check if point is outside ellipse
            xs_out.append(x_point)
            ys_out.append(y_point)
            location=0
        else:
            xs_in.append(x_point)
            ys_in.append(y_point)
            location=1
        d=[]    # empty list d
    
    if scatter=='yes':
        plt.scatter(xs_out,ys_out,c='blue',s=5)
        plt.scatter(xs_in,ys_in,c='red',s=5)

    return location

